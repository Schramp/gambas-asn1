//! SEQUENCE encode/decode — X.680 §24, X.690 §8.9.
//!
//! Table-driven, mirroring `SequenceBerHandler`
//! (`runtime/src/BerCodec.cpp`) and `SequenceSpec`/`MemberDescriptor`
//! (`runtime/include/asn1cpp/TypeDescriptor.hpp`): `encode_sequence`/
//! `decode_sequence` are generic, driven entirely by a `SequenceSpec<T>`
//! table — no per-type codegen'd traversal logic, no `switch`/`if` chains.
//! Member access goes through `MemberDescriptor`'s accessor functions
//! (`value.rs`'s module docs explain why every member uses a function, not
//! an `offsetof`-equivalent, unlike the C++ side's required-member fast path).
//!
//! `Point` (in `tests` below) is both the worked example and this module's
//! own test subject — it's real, table-driven code (not a stand-in), same
//! role as `test_seq_simple.cpp` on the C++ side and generated by
//! `RustBackend` for real ASN.1 schemas. Test-only (`#[cfg(test)]`, not
//! part of this crate's public API) — a worked example doesn't need to be
//! a permanent public type just to be readable as one.

use crate::reader::{DecodeError, Reader};
use crate::tag::{universal, Tag};
use crate::value::Asn1Value;
use crate::writer::write_constructed;
use crate::xer::XerReader;

pub const SEQUENCE_TAG: Tag = Tag::universal(universal::SEQUENCE, true);

/// SET's own natural tag (X.680 §26, universal 17,
/// constructed) — a SET-typed `SequenceSpec<T>` must use this instead of
/// `SEQUENCE_TAG`. `encode_sequence`/`decode_sequence` don't otherwise
/// distinguish SET from SEQUENCE (same TLV shape, same member walk; X.690
/// §8.11/§8.12 SET encoding is canonically member-tag-ordered on the wire,
/// which this crate doesn't enforce — same simplifying scope note
/// `decode_sequence`'s own doc already makes for member ordering generally).
pub const SET_TAG: Tag = Tag::universal(universal::SET, true);

/// One row in a `SequenceSpec<T>` table — mirrors `MemberDescriptor`
/// (`TypeDescriptor.hpp`), minus everything not yet needed by this crate's
/// scope (EXPLICIT/IMPLICIT tagging beyond the member's own natural tag,
/// CHOICE alternative dispatch — real gaps, not silently dropped:
/// `Backend`/codegen simply doesn't emit members needing them yet).
pub struct MemberDescriptor<T: 'static> {
    pub name: &'static str,
    pub tag: Tag,
    pub optional: bool,
    pub access: MemberAccess<T>,
    /// `Some` for a DEFAULT-valued member (X.680 §25.1) whose default value
    /// this crate can represent — mirrors `MemberDescriptor::set_default`
    /// (`TypeDescriptor.hpp`)/`SequenceBerHandler::decode_body`'s own
    /// `if (mbr.set_default) mbr.set_default(dest);` (`BerCodec.cpp`):
    /// `decode_sequence_content` calls this when the member's tag is absent
    /// from the wire, filling the schema default instead of leaving the
    /// field however `T::default()` left it. `None` for every other
    /// member, DEFAULT-valued or not — same "optional discriminant" shape
    /// `access`'s own variants use. No encode-side suppression: BER (unlike
    /// DER) never requires omitting a DEFAULT-equal value, and the C++
    /// runtime's own `SequenceBerHandler::encode` doesn't attempt it either
    /// (`default_value_cmp`, `TypeDescriptor.hpp`, is PER-only) — so a
    /// decoded-then-re-encoded DEFAULT member may legitimately gain an
    /// explicit tag it didn't have on the original wire, matching C++'s own
    /// behavior exactly, not a Rust-specific gap.
    pub set_default: Option<fn(&mut T)>,
}

/// How a member's value is reached and (de)serialized.
///
/// `Scalar` is the most common shape: the member is one field whose own
/// concrete type already implements `Asn1Value` (`i64`, `bool`, `Vec<u8>`,
/// `String`, an `Option<V>`/newtype-string, `SeqOf<T>`/`SetOf<T>` for a
/// SEQUENCE OF/SET OF member — every kind `rust_member_ber_tag` currently
/// covers), reached via the same accessor-function pair the crate has
/// always used (`value.rs`'s module doc explains why a function, not an
/// `offsetof`-equivalent). A SEQUENCE OF/SET OF member's field type is
/// `SeqOf<T>`/`SetOf<T>` rather than a raw `Vec<ElementType>` precisely so
/// it has a real `Asn1Value` impl and folds into this ordinary
/// `Scalar`/`TaggedScalar`/`ExplicitScalar` dispatch, with no special-casing
/// needed anywhere here.
pub enum MemberAccess<T: 'static> {
    Scalar {
        get: fn(&T) -> &dyn Asn1Value,
        get_mut: fn(&mut T) -> &mut dyn Asn1Value,
    },
    /// IMPLICIT tag override (X.690 §8.14). A member
    /// declared with its own `[n]` tag (explicit-in-the-schema, or an
    /// AUTOMATIC TAGS-assigned one) has that tag *replace* its type's
    /// natural one on the wire. Same shape as `Scalar` (`get`/`get_mut`,
    /// no closures) — the walker (`encode_sequence_content`/
    /// `decode_sequence_content` below) calls `Asn1Value::
    /// ber_encode_tagged`/`ber_decode_into_tagged` with the member's own
    /// `tag` field instead of the plain `ber_encode`/`ber_decode_into`
    /// `Scalar` uses; one generic trait method (`value.rs`) covers every
    /// kind, so no per-kind `*_tagged` primitive selection is needed here
    /// (or in codegen) at all. XER is unaffected either way — XER element
    /// tags are always field-name-derived, never type-derived (`xer.rs`'s
    /// module doc), so `get`/`get_mut` alone are already correct for that leg.
    TaggedScalar {
        get: fn(&T) -> &dyn Asn1Value,
        get_mut: fn(&mut T) -> &mut dyn Asn1Value,
    },
    /// EXPLICIT tagging (X.690 §8.14.3) — wraps the member's natural
    /// encoding in an outer TLV, rather than substituting the tag like
    /// `TaggedScalar`. Needs its own closures, unlike `TaggedScalar`:
    /// `value::decode_explicit` *constructs* a fresh value
    /// (`T: Asn1Value + Default`, monomorphized on the member's concrete
    /// type), it can't decode in place through a `&mut dyn Asn1Value`
    /// trait object the way `ber_decode_into_tagged` does — a trait object
    /// has no way to hand back a concrete, constructible `Self`. `get`/
    /// `get_mut` are carried too, XER-only (same field-name-derived-tag
    /// reasoning as `TaggedScalar` — EXPLICIT is purely a BER concept).
    ExplicitScalar {
        ber_encode: fn(&T, &mut Vec<u8>),
        ber_decode_into: fn(&mut T, &mut Reader) -> Result<(), DecodeError>,
        get: fn(&T) -> &dyn Asn1Value,
        get_mut: fn(&mut T) -> &mut dyn Asn1Value,
    },
    /// A `[n] ANY` member — X.208 legacy type, not defined in the current
    /// standard (X.680/X.690 don't mention it; X.691's own note treats a
    /// legacy ANY as an open type). No discriminant of its own (unlike
    /// CHOICE or a real open type keyed by a companion field) — an ANY
    /// member is not "one of several known types", it's raw captured bytes
    /// with no schema-visible way to know what they are. Always
    /// EXPLICIT-tagged when tagged (see `value::encode_explicit_any`'s
    /// doc) — field type is `Vec<u8>`, same Rust type as OCTET STRING, but
    /// holding raw captured TLV bytes rather than OCTET STRING content, so
    /// it can't reuse `Vec<u8>`'s own `Asn1Value` impl (that would wrap
    /// the capture in an extra OCTET STRING TLV). Mirrors the C++ side's
    /// `AnyBerHandler`/`asn_DEF_Any` (`runtime/src/BerCodec.cpp`/
    /// `BuiltinTypes.cpp`), which represent ANY the same way: an
    /// EXPLICIT-tagged member (`is_explicit = true` in the generated
    /// `MemberDescriptor`) storing raw bytes (`TypeLifecycleOps(TypeTag<
    /// OctetString>{})`), not a typed value. BER-only: ANY has no defined
    /// XER form here, no `get`/`get_mut`.
    ExplicitAny {
        ber_encode: fn(&T, &mut Vec<u8>),
        ber_decode_into: fn(&mut T, &mut Reader) -> Result<(), DecodeError>,
    },
    /// A member whose type/tag/optionality combination genuinely has no
    /// `Asn1Value` coverage yet in this crate. Every generated SEQUENCE/SET
    /// always gets a real table and `Asn1Value` impl now — nothing gates
    /// emission on every member being individually wire-representable
    /// first — so a member that isn't (a builtin storage/tag combination
    /// not yet implemented, or a member whose presence can't be safely
    /// detected at all, e.g. OPTIONAL typed by an untagged CHOICE with no
    /// tag to peek for) gets this instead: a struct containing one simply
    /// can't be successfully encoded/decoded via the generated methods
    /// yet, but every *other* member is unaffected, and — the actual
    /// point — any type that merely *references* this one as a composite
    /// member gets real coverage of its own regardless, since `Asn1Value`
    /// is always implemented, just not always successfully callable. No
    /// presence-detection is attempted (there's nothing safe to peek for
    /// in the cases that reach here) — reaching this row during either
    /// encode or decode panics unconditionally.
    Unsupported {
        reason: &'static str,
    },
}

/// Shared SEQUENCE-OF wire logic — one outer `SEQUENCE_TAG` TLV wrapping
/// zero or more inner element TLVs (X.690 §8.9); `SeqOf<T>::ber_encode_content`/
/// `ber_decode_content` (this module) delegate here, and `SetOf<T>`'s own
/// impl reuses the same content logic under its own `SET_TAG` (mirrors
/// `write_char_string`/`read_char_string` in `strings.rs` — one generic
/// function, many thin per-type call sites).
pub fn encode_seq_of<V: Asn1Value>(out: &mut Vec<u8>, items: &[V]) {
    encode_seq_of_tagged(out, SEQUENCE_TAG, items);
}

pub fn decode_seq_of<V: Asn1Value + Default>(r: &mut Reader) -> Result<Vec<V>, DecodeError> {
    decode_seq_of_tagged(r, SEQUENCE_TAG)
}

/// IMPLICIT tag override for a SEQUENCE OF/SET OF member,
/// same reasoning as `boolean::write_boolean_tagged`/`read_boolean_tagged`
/// — a member declared with its own `[n]` tag replaces the
/// natural `SEQUENCE_TAG`/`SET_TAG` on the *outer* TLV only; element
/// encoding/decoding is unaffected (elements keep their own natural tags).
pub fn encode_seq_of_tagged<V: Asn1Value>(out: &mut Vec<u8>, tag: Tag, items: &[V]) {
    let mut content = Vec::new();
    encode_seq_of_content(&mut content, items);
    write_constructed(out, tag, &content);
}

pub fn decode_seq_of_tagged<V: Asn1Value + Default>(
    r: &mut Reader,
    tag: Tag,
) -> Result<Vec<V>, DecodeError> {
    let tlv = r.read_tlv()?;
    if tlv.tag != tag {
        return Err(DecodeError::new(format!("expected SEQUENCE OF tag, got {:?}", tlv.tag), r.pos()));
    }
    decode_seq_of_content(tlv.value)
}

/// Content octets only (X.690 §8.9/§8.12) — the concatenation of each
/// element's own complete encoding, no outer TLV — for a named top-level
/// SEQUENCE OF/SET OF type's own `Asn1Value::ber_encode_content` (a real
/// newtype, not a plain alias, so it can implement the trait itself
/// exactly like SEQUENCE/CHOICE do — codegen wraps `Vec<V>` in
/// `pub struct X(pub Vec<V>);` for any *named* SEQUENCE OF/SET OF, since a
/// plain `pub type X = Vec<V>;` alias can't carry its own impl distinct
/// from whatever other ASN.1 type might also resolve to `Vec<V>`).
pub fn encode_seq_of_content<V: Asn1Value>(content: &mut Vec<u8>, items: &[V]) {
    for item in items {
        item.ber_encode(content);
    }
}

pub fn decode_seq_of_content<V: Asn1Value + Default>(content: &[u8]) -> Result<Vec<V>, DecodeError> {
    let mut inner = Reader::new(content);
    let mut result = Vec::new();
    while !inner.at_end() {
        let mut item = V::default();
        item.ber_decode_into(&mut inner)?;
        result.push(item);
    }
    Ok(result)
}

/// XER SEQUENCE-OF content: X.693 §12 wraps each element in a tag, all
/// nested directly inside the member's own `<name>...</name>` (no extra
/// container) — mirrors `SeqOfXerHandler` (`runtime/src/XerCodec.cpp`).
/// Per-element tag shape is delegated to `Asn1Value::xer_encode_seqof_element`
/// (builtin/composite: `<elem_name>content</elem_name>`; ENUMERATED/CHOICE/
/// NULL: their own self-delimiting form, no wrapper) — no codegen decision
/// required here for that split; `name_override` only ever matters to the
/// wrapped-form default.
pub fn encode_seq_of_xer<V: Asn1Value>(out: &mut String, items: &[V], depth: usize) {
    encode_seq_of_xer_named(out, items, depth, None);
}

/// `name_override` is `Some` for a SEQUENCE OF/SET OF that declared an
/// X.693 §12 element identifier (e.g. `SEQUENCE OF id INTEGER`) — the
/// generated top-level SeqOf newtype's own `xer_encode` passes
/// `SeqOfSpec::elem_xer_name` through here (see `emit_seq_of_definition`,
/// RustBackend.cpp). ENUMERATED/CHOICE/NULL elements ignore it (X.693
/// always uses their own self-delimiting tag regardless — `Generator.cpp`
/// doesn't even set `elem_xer_name` for a NULL element in the first place).
///
/// `depth` is *this collection's own* depth (matching `Asn1Value::
/// xer_encode`'s own "argument = my position" convention). Every element
/// writes its own leading `\n` + indent at `depth + 1`
/// (`Asn1Value::xer_encode_seqof_element`'s own doc) — most kinds add
/// nothing after their own closing tag, relying on the *next* element's
/// leading `\n` (or, for the last element, this function's own trailing
/// bit below) as the separator. CHOICE is the one exception: its own
/// element (`xer_encode_seqof_element`'s CHOICE override) adds a trailing
/// `\n` of its own too, matching `ChoiceXerHandler`'s own unconditional
/// `... << "</" << alt.name << ">\n"` (`runtime/src/XerCodec.cpp`) — when
/// two CHOICE elements sit back to back, that produces a genuine blank
/// line between them (confirmed against a real schema:
/// `Messaging-Property ::= CHOICE` used as a `SET OF` element — not a
/// bug, `SeqOfXerHandler`'s own loop only special-cases *its own* leading
/// newline for a non-CHOICE element, `if (!edef.choice_spec) { ...
/// os << s.indent(1); }`, so two adjacent CHOICE elements each
/// unconditionally contribute their own leading *and* trailing newline
/// with nothing to deduplicate them).
///
/// This function's own trailing bit — `\n` + `indent(depth)`, iff at
/// least one element was written (an empty collection contributes
/// nothing at all, matching `SeqOfXerHandler`'s own `count == 0` case —
/// the caller's `<name></name>` results automatically with no special
/// case needed here, same reasoning `encode_sequence_xer_content`'s own
/// empty-content case gives) — only adds the `\n` when the last element
/// didn't already end with one (CHOICE's own case): otherwise the two
/// would combine into an unwanted blank line right before the closing
/// tag, which real ground-truth output never has.
pub fn encode_seq_of_xer_named<V: Asn1Value>(out: &mut String, items: &[V], depth: usize, name_override: Option<&str>) {
    let start = out.len();
    for item in items {
        item.xer_encode_seqof_element(out, depth, name_override);
    }
    if out.len() > start {
        if !out.ends_with('\n') {
            out.push('\n');
        }
        out.push_str(&crate::xer::indent(depth));
    }
}

pub fn decode_seq_of_xer<V: Asn1Value + Default>(r: &mut XerReader) -> Result<Vec<V>, DecodeError> {
    decode_seq_of_xer_named(r, None)
}

/// Decode counterpart of `encode_seq_of_xer_named`. Loop termination is
/// purely "next tag is a closing tag" (mirrors `SeqOfXerHandler::decode`'s
/// `ti.closing && ti.name == def.name` check — the outer `<name>...</name>`
/// is already consumed by the caller before/after this runs, same as
/// there), not a per-element name comparison: the element's own tag varies
/// per item for ENUMERATED (value name) and CHOICE (chosen alternative),
/// so a fixed-name peek would wrongly stop after the first element.
pub fn decode_seq_of_xer_named<V: Asn1Value + Default>(r: &mut XerReader, name_override: Option<&str>) -> Result<Vec<V>, DecodeError> {
    let mut result = Vec::new();
    loop {
        let peeked = r.peek_tag();
        if peeked.closing || peeked.name.is_empty() {
            break;
        }
        let mut item = V::default();
        item.xer_decode_into_seqof_element(r, name_override)?;
        result.push(item);
    }
    Ok(result)
}

/// Generic SEQUENCE OF wrapper (see `SetOf<T>` just below for the SET OF
/// sibling) — gives a *named* SEQUENCE OF CHOICE alternative
/// (`RustBackend::rust_seqof_alt_mtype`) or SEQUENCE/SET *member*
/// (`RustBackend::emit_sequence_declaration`, both `compiler/src/codegen/
/// RustBackend.cpp`) a concrete `Asn1Value` impl without per-occurrence
/// codegen. A bare `Vec<T>` can't get one generically: a blanket
/// `impl<V: Asn1Value> Asn1Value for Vec<V>` would coherence-conflict with
/// `Vec<u8>`'s own concrete OCTET STRING impl (E0119 — at most one
/// unconstrained blanket impl per trait per crate). `SeqOf<T>` sidesteps
/// that by being a distinct type nothing else implements, so one blanket
/// impl below covers every element type — no per-occurrence synthesized
/// wrapper struct needed the way a top-level named `X ::= SEQUENCE OF Y`
/// still gets from `emit_seq_of_definition` (that one keeps its own real
/// ASN.1 name for XER wrapping when referenced elsewhere; a `SeqOf<T>`
/// alternative/member is wrapped by its own alternative/field name
/// instead, same as any other scalar member — never needs a name of its
/// own, hence `xer_element_name` below being a generic placeholder).
///
/// `ber_natural_tag` genuinely matters here, unlike a bare CHOICE
/// alternative (which always dispatches through its own resolved tag via
/// `ber_encode_tagged`/`ber_decode_into_tagged`, never this method): a
/// required SEQUENCE/SET *member* with no tag override goes through the
/// ordinary `MemberAccess::Scalar` path, whose `ber_encode`/`ber_decode_into`
/// (the `Asn1Value` trait's own default methods) reach for
/// `self.ber_natural_tag()` directly — and an EXPLICIT-tagged member's
/// inner TLV (X.690 §8.14.3: EXPLICIT wraps the value's own natural
/// encoding unchanged) reaches it exactly the same way through
/// `value::encode_explicit`/`decode_explicit`. `SeqOf<T>`/`SetOf<T>` being
/// two distinct types with two different `ber_natural_tag()` values is
/// what makes both paths correct automatically, with no separate
/// SEQUENCE-vs-SET signal needed anywhere in the generic walker
/// (`sequence.rs`/`xer.rs`) — RustBackend only has to pick which of the
/// two type names to put in the struct field declaration.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct SeqOf<T>(pub Vec<T>);

impl<T> std::ops::Deref for SeqOf<T> {
    type Target = Vec<T>;
    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl<T> std::ops::DerefMut for SeqOf<T> {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.0
    }
}

impl<T: Asn1Value + Default> Asn1Value for SeqOf<T> {
    fn ber_natural_tag(&self) -> Tag {
        SEQUENCE_TAG
    }

    fn xer_element_name(&self) -> &'static str {
        "SEQUENCE-OF"
    }

    fn ber_encode_content(&self, out: &mut Vec<u8>) {
        encode_seq_of_content(out, &self.0);
    }

    fn ber_decode_content(&mut self, content: &[u8]) -> Result<(), DecodeError> {
        self.0 = decode_seq_of_content(content)?;
        Ok(())
    }

    fn xer_encode(&self, out: &mut String, depth: usize) {
        encode_seq_of_xer(out, &self.0, depth);
    }

    fn xer_decode_into(&mut self, r: &mut XerReader) -> Result<(), DecodeError> {
        self.0 = decode_seq_of_xer(r)?;
        Ok(())
    }
}

