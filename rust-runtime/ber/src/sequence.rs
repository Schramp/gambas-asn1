//! SEQUENCE encode/decode — X.680 §24, X.690 §8.9.
//!
//! Table-driven, mirroring `SequenceBerHandler`
//! (`runtime/src/BerCodec.cpp`) and `SequenceSpec`/`MemberDescriptor`
//! (`runtime/include/asn1cpp/TypeDescriptor.hpp`): `encode_sequence`/
//! `decode_sequence` are generic, driven entirely by a `SequenceSpec<T>`
//! table — no per-type codegen'd traversal logic, no `switch`/`if` chains.
//! Member access goes through `MemberDescriptor`'s accessor functions
//! (`value.rs`'s module docs explain why every member uses a function, not
//! an `offsetof`-equivalent, unlike the C++ side's required-member fast path).
//!
//! `Point` below is both the worked example and this module's own test
//! subject — it's real, table-driven code (not a stand-in), same role as
//! `test_seq_simple.cpp` on the C++ side and generated by `RustBackend` for
//! real ASN.1 schemas.

use crate::reader::{DecodeError, Reader};
use crate::tag::{universal, Tag};
use crate::value::Asn1Value;
use crate::writer::write_constructed;
use crate::xer::XerReader;

pub const SEQUENCE_TAG: Tag = Tag::universal(universal::SEQUENCE, true);

/// SET's own natural tag (X.680 §26, universal 17,
/// constructed) — a SET-typed `SequenceSpec<T>` must use this instead of
/// `SEQUENCE_TAG`. `encode_sequence`/`decode_sequence` don't otherwise
/// distinguish SET from SEQUENCE (same TLV shape, same member walk; X.690
/// §8.11/§8.12 SET encoding is canonically member-tag-ordered on the wire,
/// which this crate doesn't enforce — same simplifying scope note
/// `decode_sequence`'s own doc already makes for member ordering generally).
pub const SET_TAG: Tag = Tag::universal(universal::SET, true);

/// One row in a `SequenceSpec<T>` table — mirrors `MemberDescriptor`
/// (`TypeDescriptor.hpp`), minus everything not yet needed by this crate's
/// scope (DEFAULT values, EXPLICIT/IMPLICIT tagging beyond the member's own
/// natural tag, CHOICE alternative dispatch — all real gaps, not silently
/// dropped: `Backend`/codegen simply doesn't emit members needing them yet).
pub struct MemberDescriptor<T: 'static> {
    pub name: &'static str,
    pub tag: Tag,
    pub optional: bool,
    pub access: MemberAccess<T>,
}

/// How a member's value is reached and (de)serialized.
///
/// `Scalar` is the original, and by far the most common, shape: the member
/// is one field whose own concrete type already implements `Asn1Value`
/// (`i64`, `bool`, `Vec<u8>`, `String`, an `Option<V>`/newtype-string —
/// every kind `rust_member_ber_tag` currently covers), reached via the same
/// accessor-function pair the crate has always used (`value.rs`'s module
/// doc explains why a function, not an `offsetof`-equivalent).
///
/// `SeqOf` is new: a SEQUENCE OF member's field type is `Vec<ElementType>`,
/// which — deliberately — does *not* implement `Asn1Value` itself (unlike
/// `Option<V>`'s blanket impl): `Vec<u8>` already has its
/// own *concrete* `Asn1Value` impl for OCTET STRING content, and Rust's
/// coherence rules forbid also giving `Vec<u8>` an overlapping instantiation
/// of a generic `impl<V: Asn1Value> Asn1Value for Vec<V>` (the compiler
/// can't rule out some future crate adding `impl Asn1Value for u8`, so it
/// rejects the ambiguity up front, not just when it would actually occur).
/// `SeqOf`'s four closures encode/decode the whole `Vec<ElementType>` field
/// directly instead — same closure-over-the-concrete-type shape
/// `ChoiceAlternativeSpec` (`choice.rs`) already established for a
/// structurally different reason (multiple types sharing one table).
pub enum MemberAccess<T: 'static> {
    Scalar {
        get: fn(&T) -> &dyn Asn1Value,
        get_mut: fn(&mut T) -> &mut dyn Asn1Value,
    },
    SeqOf {
        ber_encode: fn(&T, &mut Vec<u8>),
        ber_decode_into: fn(&mut T, &mut Reader) -> Result<(), DecodeError>,
        xer_encode: fn(&T, &mut String),
        xer_decode_into: fn(&mut T, &mut XerReader) -> Result<(), DecodeError>,
    },
    /// IMPLICIT tag override (X.690 §8.14). A member
    /// declared with its own `[n]` tag (explicit-in-the-schema, or an
    /// AUTOMATIC TAGS-assigned one) has that tag *replace* its type's
    /// natural one on the wire. Same shape as `Scalar` (`get`/`get_mut`,
    /// no closures) — the walker (`encode_sequence_content`/
    /// `decode_sequence_content` below) calls `Asn1Value::
    /// ber_encode_tagged`/`ber_decode_into_tagged` with the member's own
    /// `tag` field instead of the plain `ber_encode`/`ber_decode_into`
    /// `Scalar` uses; one generic trait method (`value.rs`) covers every
    /// kind, so no per-kind `*_tagged` primitive selection is needed here
    /// (or in codegen) at all. XER is unaffected either way — XER element
    /// tags are always field-name-derived, never type-derived (`xer.rs`'s
    /// module doc), so `get`/`get_mut` alone are already correct for that leg.
    TaggedScalar {
        get: fn(&T) -> &dyn Asn1Value,
        get_mut: fn(&mut T) -> &mut dyn Asn1Value,
    },
    /// EXPLICIT tagging (X.690 §8.14.3) — wraps the member's natural
    /// encoding in an outer TLV, rather than substituting the tag like
    /// `TaggedScalar`. Needs its own closures, unlike `TaggedScalar`:
    /// `value::decode_explicit` *constructs* a fresh value
    /// (`T: Asn1Value + Default`, monomorphized on the member's concrete
    /// type), it can't decode in place through a `&mut dyn Asn1Value`
    /// trait object the way `ber_decode_into_tagged` does — a trait object
    /// has no way to hand back a concrete, constructible `Self`. `get`/
    /// `get_mut` are carried too, XER-only (same field-name-derived-tag
    /// reasoning as `TaggedScalar` — EXPLICIT is purely a BER concept).
    ExplicitScalar {
        ber_encode: fn(&T, &mut Vec<u8>),
        ber_decode_into: fn(&mut T, &mut Reader) -> Result<(), DecodeError>,
        get: fn(&T) -> &dyn Asn1Value,
        get_mut: fn(&mut T) -> &mut dyn Asn1Value,
    },
    /// `SeqOf`'s analogue of `TaggedScalar` — a SEQUENCE OF/
    /// SET OF member declared with its own `[n]` tag. `ber_encode`/
    /// `ber_decode_into` call `encode_seq_of_tagged`/`decode_seq_of_tagged`
    /// with the member's real resolved tag instead of `SeqOf`'s hardcoded
    /// `SEQUENCE_TAG`. XER is unaffected (reuses `SeqOf`'s `xer_encode`/
    /// `xer_decode_into` unchanged — same field-name-derived-tag reasoning
    /// as `TaggedScalar`).
    TaggedSeqOf {
        ber_encode: fn(&T, &mut Vec<u8>),
        ber_decode_into: fn(&mut T, &mut Reader) -> Result<(), DecodeError>,
        xer_encode: fn(&T, &mut String),
        xer_decode_into: fn(&mut T, &mut XerReader) -> Result<(), DecodeError>,
    },
    /// A `[n] ANY` member — X.208 legacy type, not defined in the current
    /// standard (X.680/X.690 don't mention it; X.691's own note treats a
    /// legacy ANY as an open type). No discriminant of its own (unlike
    /// CHOICE or a real open type keyed by a companion field) — an ANY
    /// member is not "one of several known types", it's raw captured bytes
    /// with no schema-visible way to know what they are. Always
    /// EXPLICIT-tagged when tagged (see `value::encode_explicit_any`'s
    /// doc) — field type is `Vec<u8>`, same Rust type as OCTET STRING, but
    /// holding raw captured TLV bytes rather than OCTET STRING content, so
    /// it can't reuse `Vec<u8>`'s own `Asn1Value` impl (that would wrap
    /// the capture in an extra OCTET STRING TLV). Mirrors the C++ side's
    /// `AnyBerHandler`/`asn_DEF_Any` (`runtime/src/BerCodec.cpp`/
    /// `BuiltinTypes.cpp`), which represent ANY the same way: an
    /// EXPLICIT-tagged member (`is_explicit = true` in the generated
    /// `MemberDescriptor`) storing raw bytes (`TypeLifecycleOps(TypeTag<
    /// OctetString>{})`), not a typed value. BER-only: ANY has no defined
    /// XER form here, no `get`/`get_mut`.
    ExplicitAny {
        ber_encode: fn(&T, &mut Vec<u8>),
        ber_decode_into: fn(&mut T, &mut Reader) -> Result<(), DecodeError>,
    },
    /// A member whose type/tag/optionality combination genuinely has no
    /// `Asn1Value` coverage yet in this crate. Every generated SEQUENCE/SET
    /// always gets a real table and `Asn1Value` impl now — nothing gates
    /// emission on every member being individually wire-representable
    /// first — so a member that isn't (a builtin storage/tag combination
    /// not yet implemented, or a member whose presence can't be safely
    /// detected at all, e.g. OPTIONAL typed by an untagged CHOICE with no
    /// tag to peek for) gets this instead: a struct containing one simply
    /// can't be successfully encoded/decoded via the generated methods
    /// yet, but every *other* member is unaffected, and — the actual
    /// point — any type that merely *references* this one as a composite
    /// member gets real coverage of its own regardless, since `Asn1Value`
    /// is always implemented, just not always successfully callable. No
    /// presence-detection is attempted (there's nothing safe to peek for
    /// in the cases that reach here) — reaching this row during either
    /// encode or decode panics unconditionally.
    Unsupported {
        reason: &'static str,
    },
}

/// Shared SEQUENCE-OF wire logic — one outer `SEQUENCE_TAG` TLV wrapping
/// zero or more inner element TLVs (X.690 §8.9), used by every codegen'd
/// `MemberAccess::SeqOf::ber_encode`/`ber_decode_into` closure regardless of
/// element type (mirrors `write_char_string`/`read_char_string` in
/// `strings.rs` — one generic function, many thin per-type call sites).
pub fn encode_seq_of<V: Asn1Value>(out: &mut Vec<u8>, items: &[V]) {
    encode_seq_of_tagged(out, SEQUENCE_TAG, items);
}

pub fn decode_seq_of<V: Asn1Value + Default>(r: &mut Reader) -> Result<Vec<V>, DecodeError> {
    decode_seq_of_tagged(r, SEQUENCE_TAG)
}

/// IMPLICIT tag override for a SEQUENCE OF/SET OF member,
/// same reasoning as `boolean::write_boolean_tagged`/`read_boolean_tagged`
/// — a member declared with its own `[n]` tag replaces the
/// natural `SEQUENCE_TAG`/`SET_TAG` on the *outer* TLV only; element
/// encoding/decoding is unaffected (elements keep their own natural tags).
pub fn encode_seq_of_tagged<V: Asn1Value>(out: &mut Vec<u8>, tag: Tag, items: &[V]) {
    let mut content = Vec::new();
    encode_seq_of_content(&mut content, items);
    write_constructed(out, tag, &content);
}

pub fn decode_seq_of_tagged<V: Asn1Value + Default>(
    r: &mut Reader,
    tag: Tag,
) -> Result<Vec<V>, DecodeError> {
    let tlv = r.read_tlv()?;
    if tlv.tag != tag {
        return Err(DecodeError::new(format!("expected SEQUENCE OF tag, got {:?}", tlv.tag), r.pos()));
    }
    decode_seq_of_content(tlv.value)
}

/// Content octets only (X.690 §8.9/§8.12) — the concatenation of each
/// element's own complete encoding, no outer TLV — for a named top-level
/// SEQUENCE OF/SET OF type's own `Asn1Value::ber_encode_content` (a real
/// newtype, not a plain alias, so it can implement the trait itself
/// exactly like SEQUENCE/CHOICE do — codegen wraps `Vec<V>` in
/// `pub struct X(pub Vec<V>);` for any *named* SEQUENCE OF/SET OF, since a
/// plain `pub type X = Vec<V>;` alias can't carry its own impl distinct
/// from whatever other ASN.1 type might also resolve to `Vec<V>`).
pub fn encode_seq_of_content<V: Asn1Value>(content: &mut Vec<u8>, items: &[V]) {
    for item in items {
        item.ber_encode(content);
    }
}

pub fn decode_seq_of_content<V: Asn1Value + Default>(content: &[u8]) -> Result<Vec<V>, DecodeError> {
    let mut inner = Reader::new(content);
    let mut result = Vec::new();
    while !inner.at_end() {
        let mut item = V::default();
        item.ber_decode_into(&mut inner)?;
        result.push(item);
    }
    Ok(result)
}

/// XER SEQUENCE-OF content: X.693 §12 wraps each element in a tag, all
/// nested directly inside the member's own `<name>...</name>` (no extra
/// container) — mirrors `SeqOfXerHandler` (`runtime/src/XerCodec.cpp`).
/// Per-element tag shape is delegated to `Asn1Value::xer_encode_seqof_element`
/// (builtin/composite: `<elem_name>content</elem_name>`; ENUMERATED/CHOICE/
/// NULL: their own self-delimiting form, no wrapper) — no codegen decision
/// required here for that split; `name_override` only ever matters to the
/// wrapped-form default.
pub fn encode_seq_of_xer<V: Asn1Value>(out: &mut String, items: &[V]) {
    encode_seq_of_xer_named(out, items, None);
}

/// `name_override` is `Some` for a SEQUENCE OF/SET OF that declared an
/// X.693 §12 element identifier (e.g. `SEQUENCE OF id INTEGER`) — the
/// generated top-level SeqOf newtype's own `xer_encode` passes
/// `SeqOfSpec::elem_xer_name` through here (see `emit_seq_of_definition`,
/// RustBackend.cpp). ENUMERATED/CHOICE/NULL elements ignore it (X.693
/// always uses their own self-delimiting tag regardless — `Generator.cpp`
/// doesn't even set `elem_xer_name` for a NULL element in the first place).
pub fn encode_seq_of_xer_named<V: Asn1Value>(out: &mut String, items: &[V], name_override: Option<&str>) {
    for item in items {
        item.xer_encode_seqof_element(out, name_override);
    }
}

pub fn decode_seq_of_xer<V: Asn1Value + Default>(r: &mut XerReader) -> Result<Vec<V>, DecodeError> {
    decode_seq_of_xer_named(r, None)
}

/// Decode counterpart of `encode_seq_of_xer_named`. Loop termination is
/// purely "next tag is a closing tag" (mirrors `SeqOfXerHandler::decode`'s
/// `ti.closing && ti.name == def.name` check — the outer `<name>...</name>`
/// is already consumed by the caller before/after this runs, same as
/// there), not a per-element name comparison: the element's own tag varies
/// per item for ENUMERATED (value name) and CHOICE (chosen alternative),
/// so a fixed-name peek would wrongly stop after the first element.
pub fn decode_seq_of_xer_named<V: Asn1Value + Default>(r: &mut XerReader, name_override: Option<&str>) -> Result<Vec<V>, DecodeError> {
    let mut result = Vec::new();
    loop {
        let peeked = r.peek_tag();
        if peeked.closing || peeked.name.is_empty() {
            break;
        }
        let mut item = V::default();
        item.xer_decode_into_seqof_element(r, name_override)?;
        result.push(item);
    }
    Ok(result)
}

/// Generic SEQUENCE OF/SET OF wrapper — gives a *named* SEQUENCE OF (or SET
/// OF) CHOICE alternative (`RustBackend::rust_seqof_alt_mtype`,
/// `compiler/src/codegen/RustBackend.cpp`) a concrete `Asn1Value` impl
/// without per-occurrence codegen. A bare `Vec<T>` can't get one
/// generically: a blanket `impl<V: Asn1Value> Asn1Value for Vec<V>` would
/// coherence-conflict with `Vec<u8>`'s own concrete OCTET STRING impl
/// (E0119 — at most one unconstrained blanket impl per trait per crate).
/// `SeqOf<T>` sidesteps that by being a distinct type nothing else
/// implements, so one blanket impl below covers every element type — no
/// per-occurrence synthesized wrapper struct needed the way a top-level
/// named `X ::= SEQUENCE OF Y` still gets from `emit_seq_of_definition`
/// (that one keeps its own real ASN.1 name for XER wrapping when
/// referenced elsewhere; a `SeqOf<T>` alternative is wrapped by its own
/// alternative name instead, same as any other scalar alternative — never
/// needs a name of its own, hence `ber_natural_tag`/`xer_element_name`
/// below being generic placeholders: a CHOICE alternative always dispatches
/// through its own resolved tag via `ber_encode_tagged`/
/// `ber_decode_into_tagged`, never these, so SET OF's own universal 17 tag
/// vs SEQUENCE OF's 16 is immaterial here — both shapes wrap correctly).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct SeqOf<T>(pub Vec<T>);

impl<T> std::ops::Deref for SeqOf<T> {
    type Target = Vec<T>;
    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl<T> std::ops::DerefMut for SeqOf<T> {
    fn deref_mut(&mut self) -> &mut Self::Target {
        &mut self.0
    }
}

impl<T: Asn1Value + Default> Asn1Value for SeqOf<T> {
    fn ber_natural_tag(&self) -> Tag {
        SEQUENCE_TAG
    }

    fn xer_element_name(&self) -> &'static str {
        "SEQUENCE-OF"
    }

    fn ber_encode_content(&self, out: &mut Vec<u8>) {
        encode_seq_of_content(out, &self.0);
    }

    fn ber_decode_content(&mut self, content: &[u8]) -> Result<(), DecodeError> {
        self.0 = decode_seq_of_content(content)?;
        Ok(())
    }

    fn xer_encode(&self, out: &mut String) {
        encode_seq_of_xer(out, &self.0);
    }

    fn xer_decode_into(&mut self, r: &mut XerReader) -> Result<(), DecodeError> {
        self.0 = decode_seq_of_xer(r)?;
        Ok(())
    }
}

/// SEQUENCE/SET member table — mirrors `SequenceSpec` (`TypeDescriptor.hpp`).
///
/// `name` is the XER element tag for the whole SEQUENCE (mirrors
/// `TypeDescriptor::name`, used by `SequenceXerHandler` — X.693's outer
/// element is the *type* name, unlike each member's own tag which is
/// *field*-name-derived). BER doesn't need it (BER dispatch is by `tag`
/// alone), but one table drives both encodings (see `lib.rs`'s XER module
/// doc), so it lives here rather than in a second, XER-only struct.
///
/// **Deliberate layering divergence from both C++ codebases**: in
/// `runtime/include/asn1cpp/TypeDescriptor.hpp`
/// `name` lives on the outer `TypeDescriptor`, a sibling to
/// `sequence_spec`/`choice_spec`/`enum_spec` — never inside `SequenceSpec`
/// itself. Same split in asn1c (`asn_TYPE_descriptor_s::name` vs.
/// `asn_SEQUENCE_specifics_s`, which carries no name at all). That layer
/// exists in both C++ codebases because their dispatch is runtime
/// polymorphic — one `TypeDescriptor*`/`asn_TYPE_descriptor_t*` has to
/// carry `name` regardless of *which* construct (`SEQUENCE`/`CHOICE`/
/// `ENUMERATED`) it points at, since the codec picks the handler at
/// runtime via `TypeKind`/`tag2el`. Rust's design has no such layer:
/// dispatch is by generic parameter (`SequenceSpec<T>`) resolved at compile
/// time, so there is no shared runtime "type descriptor" object for `name`
/// to live on once, and introducing one here would only exist to satisfy
/// field-sharing, not to do anything. Each construct-specific spec (this
/// one, and `ChoiceSpec<T>` in `choice.rs`) carries its own
/// `name` — cheap (`&'static str`, one word, no allocation), and avoids
/// inventing indirection with no other purpose. Documented here so the
/// repetition in `ChoiceSpec<T>` reads as intentional, not a
/// copy-paste that forgot to deduplicate.
pub struct SequenceSpec<T: 'static> {
    pub name: &'static str,
    pub tag: Tag,
    pub members: &'static [MemberDescriptor<T>],
}

/// Member-loop content of a SEQUENCE encoding, without the outer TLV —
/// shared by `encode_sequence_tagged` (the top-level tag) and, once a
/// generated SEQUENCE/SET type has its own `Asn1Value` impl, by whatever
/// tag a *containing* type's member override applies (X.690 §8.14 IMPLICIT
/// retagging replaces the outer tag only, content is unchanged).
pub fn encode_sequence_content<T>(spec: &SequenceSpec<T>, value: &T, content: &mut Vec<u8>) {
    for m in spec.members {
        match &m.access {
            MemberAccess::Scalar { get, .. } => get(value).ber_encode(content),
            MemberAccess::TaggedScalar { get, .. } => get(value).ber_encode_tagged(m.tag, content),
            MemberAccess::ExplicitScalar { ber_encode, .. } => ber_encode(value, content),
            MemberAccess::SeqOf { ber_encode, .. } => ber_encode(value, content),
            MemberAccess::TaggedSeqOf { ber_encode, .. } => ber_encode(value, content),
            MemberAccess::ExplicitAny { ber_encode, .. } => ber_encode(value, content),
            MemberAccess::Unsupported { reason } => panic!("member '{}' not supported: {}", m.name, reason),
        }
    }
}

/// SEQUENCE encoding under an explicit tag override — the runtime
/// counterpart of a composite (SEQUENCE/SET-typed) member declared with its
/// own IMPLICIT `[n]` tag (X.690 §8.14.2): same content as `encode_sequence`,
/// different outer tag. Generic over any `SequenceSpec<T>`, so codegen needs
/// no per-type wiring beyond passing the member's resolved tag.
pub fn encode_sequence_tagged<T>(spec: &SequenceSpec<T>, value: &T, tag: Tag) -> Vec<u8> {
    let mut content = Vec::new();
    encode_sequence_content(spec, value, &mut content);
    let mut out = Vec::new();
    write_constructed(&mut out, tag, &content);
    out
}

/// Appends a SEQUENCE's complete TLV (its own natural tag) to an existing
/// buffer — the shape `Asn1Value::ber_encode` needs (writes into a
/// caller-owned `out`, not a fresh `Vec`) so a generated SEQUENCE/SET type
/// can implement that trait and become usable as a nested composite member.
pub fn encode_sequence_into<T>(spec: &SequenceSpec<T>, value: &T, out: &mut Vec<u8>) {
    out.extend_from_slice(&encode_sequence_tagged(spec, value, spec.tag));
}

/// Generic SEQUENCE encoder — the Rust analogue of
/// `SequenceBerHandler::encode`. Iterates `spec.members` in order, writing
/// each member's own complete TLV into the constructed SEQUENCE content.
/// OPTIONAL suppression needs no special-casing here: an
/// absent `Option<V>::None` member's `ber_encode` (the blanket
/// `Asn1Value for Option<V>` impl, `value.rs`) already writes nothing. No
/// DEFAULT-value suppression yet — a real gap, not silently dropped.
pub fn encode_sequence<T>(spec: &SequenceSpec<T>, value: &T) -> Vec<u8> {
    encode_sequence_tagged(spec, value, spec.tag)
}

/// Generic SEQUENCE decoder — the Rust analogue of
/// `SequenceBerHandler::decode`/`decode_body`. `T::default()` provides the
/// initial value (matching every generated struct's `#[derive(Default)]`);
/// each member is decoded in table order directly into its field via
/// `ber_decode_into`, no intermediate allocation per member.
///
/// OPTIONAL members: tag-presence detection, same model
/// `asn1cpp/CLAUDE.md`'s BER-vs-PER table documents ("OPTIONAL detection:
/// Tag present/absent in stream"). Peek before deciding whether to call
/// `ber_decode_into` at all — an absent optional member's tag belongs to
/// whatever comes *next* (the following member, or nothing), so the reader
/// must not be advanced past it if this member isn't present. Only a linear
/// scan (each optional member checked once, in table order) — correct for
/// SEQUENCE's canonical member ordering (X.690 §8.9), same simplifying
/// assumption `MemberDescriptor`'s module doc already documents this crate
/// making elsewhere (no DEFAULT values, no out-of-order OPTIONAL members).
pub fn decode_sequence_content<T: Default>(spec: &SequenceSpec<T>, inner: &mut Reader) -> Result<T, DecodeError> {
    let mut result = T::default();
    for m in spec.members {
        match &m.access {
            MemberAccess::Scalar { get_mut, .. } => {
                if m.optional {
                    if inner.peek_tag() == Some(m.tag) {
                        get_mut(&mut result).ber_decode_into(inner)?;
                    }
                } else {
                    get_mut(&mut result).ber_decode_into(inner)?;
                }
            }
            MemberAccess::SeqOf { ber_decode_into, .. } => {
                ber_decode_into(&mut result, inner)?;
            }
            MemberAccess::TaggedScalar { get_mut, .. } => {
                if m.optional {
                    if inner.peek_tag() == Some(m.tag) {
                        get_mut(&mut result).ber_decode_into_tagged(inner, m.tag)?;
                    }
                } else {
                    get_mut(&mut result).ber_decode_into_tagged(inner, m.tag)?;
                }
            }
            MemberAccess::ExplicitScalar { ber_decode_into, .. } => {
                if m.optional {
                    if inner.peek_tag() == Some(m.tag) {
                        ber_decode_into(&mut result, inner)?;
                    }
                } else {
                    ber_decode_into(&mut result, inner)?;
                }
            }
            MemberAccess::TaggedSeqOf { ber_decode_into, .. } => {
                ber_decode_into(&mut result, inner)?;
            }
            MemberAccess::ExplicitAny { ber_decode_into, .. } => {
                if m.optional {
                    if inner.peek_tag() == Some(m.tag) {
                        ber_decode_into(&mut result, inner)?;
                    }
                } else {
                    ber_decode_into(&mut result, inner)?;
                }
            }
            MemberAccess::Unsupported { reason } => panic!("member '{}' not supported: {}", m.name, reason),
        }
    }
    Ok(result)
}

/// SEQUENCE decoding under an explicit tag override — the decode
/// counterpart of `encode_sequence_tagged`.
pub fn decode_sequence_tagged<T: Default>(spec: &SequenceSpec<T>, r: &mut Reader, tag: Tag) -> Result<T, DecodeError> {
    let tlv = r.read_tlv()?;
    if tlv.tag != tag {
        return Err(DecodeError::new(format!("expected SEQUENCE tag, got {:?}", tlv.tag), r.pos()));
    }
    let mut inner = Reader::new(tlv.value);
    decode_sequence_content(spec, &mut inner)
}

/// Reads a SEQUENCE (its own natural tag) from the caller's current stream
/// position — the shape `Asn1Value::ber_decode_into` needs (reads the next
/// TLV from a shared `Reader`, not a standalone buffer) so a generated
/// SEQUENCE/SET type can implement that trait and become usable as a nested
/// composite member.
pub fn decode_sequence_from<T: Default>(spec: &SequenceSpec<T>, r: &mut Reader) -> Result<T, DecodeError> {
    decode_sequence_tagged(spec, r, spec.tag)
}

pub fn decode_sequence<T: Default>(spec: &SequenceSpec<T>, data: &[u8]) -> Result<T, DecodeError> {
    let mut r = Reader::new(data);
    decode_sequence_from(spec, &mut r)
}

/// `Point ::= SEQUENCE { x INTEGER, y INTEGER }`
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Point {
    pub x: i64,
    pub y: i64,
}

static POINT_MEMBERS: [MemberDescriptor<Point>; 2] = [
    MemberDescriptor {
        name: "x",
        tag: crate::integer::INTEGER_TAG,
        optional: false,
        access: MemberAccess::Scalar { get: |v| &v.x, get_mut: |v| &mut v.x },
    },
    MemberDescriptor {
        name: "y",
        tag: crate::integer::INTEGER_TAG,
        optional: false,
        access: MemberAccess::Scalar { get: |v| &v.y, get_mut: |v| &mut v.y },
    },
];

static POINT_SPEC: SequenceSpec<Point> =
    SequenceSpec { name: "Point", tag: SEQUENCE_TAG, members: &POINT_MEMBERS };

impl Point {
    pub fn encode(&self) -> Vec<u8> {
        encode_sequence(&POINT_SPEC, self)
    }

    pub fn decode(data: &[u8]) -> Result<Point, DecodeError> {
        decode_sequence(&POINT_SPEC, data)
    }

    pub fn encode_xer(&self) -> String {
        crate::xer::encode_sequence_xer(&POINT_SPEC, self)
    }

    pub fn decode_xer(xml: &str) -> Result<Point, DecodeError> {
        crate::xer::decode_sequence_xer(&POINT_SPEC, xml)
    }
}

