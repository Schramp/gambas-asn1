/// SEQUENCE/SET member table — mirrors `SequenceSpec` (`TypeDescriptor.hpp`).
///
/// `name` is the XER element tag for the whole SEQUENCE (mirrors
/// `TypeDescriptor::name`, used by `SequenceXerHandler` — X.693's outer
/// element is the *type* name, unlike each member's own tag which is
/// *field*-name-derived). BER doesn't need it (BER dispatch is by `tag`
/// alone), but one table drives both encodings (see `lib.rs`'s XER module
/// doc), so it lives here rather than in a second, XER-only struct.
///
/// **Deliberate layering divergence from both C++ codebases**: in
/// `runtime/include/asn1cpp/TypeDescriptor.hpp`
/// `name` lives on the outer `TypeDescriptor`, a sibling to
/// `sequence_spec`/`choice_spec`/`enum_spec` — never inside `SequenceSpec`
/// itself. Same split in asn1c (`asn_TYPE_descriptor_s::name` vs.
/// `asn_SEQUENCE_specifics_s`, which carries no name at all). That layer
/// exists in both C++ codebases because their dispatch is runtime
/// polymorphic — one `TypeDescriptor*`/`asn_TYPE_descriptor_t*` has to
/// carry `name` regardless of *which* construct (`SEQUENCE`/`CHOICE`/
/// `ENUMERATED`) it points at, since the codec picks the handler at
/// runtime via `TypeKind`/`tag2el`. Rust's design has no such layer:
/// dispatch is by generic parameter (`SequenceSpec<T>`) resolved at compile
/// time, so there is no shared runtime "type descriptor" object for `name`
/// to live on once, and introducing one here would only exist to satisfy
/// field-sharing, not to do anything. Each construct-specific spec (this
/// one, and `ChoiceSpec<T>` in `choice.rs`) carries its own
/// `name` — cheap (`&'static str`, one word, no allocation), and avoids
/// inventing indirection with no other purpose. Documented here so the
/// repetition in `ChoiceSpec<T>` reads as intentional, not a
/// copy-paste that forgot to deduplicate.
pub struct SequenceSpec<T: 'static> {
    pub name: &'static str,
    pub tag: Tag,
    pub members: &'static [MemberDescriptor<T>],
}

/// Member-loop content of a SEQUENCE encoding, without the outer TLV —
/// shared by `encode_sequence_tagged` (the top-level tag) and, once a
/// generated SEQUENCE/SET type has its own `Asn1Value` impl, by whatever
/// tag a *containing* type's member override applies (X.690 §8.14 IMPLICIT
/// retagging replaces the outer tag only, content is unchanged).
pub fn encode_sequence_content<T>(spec: &SequenceSpec<T>, value: &T, content: &mut Vec<u8>) {
    for m in spec.members {
        match &m.access {
            MemberAccess::Scalar { get, .. } => get(value).ber_encode(content),
            MemberAccess::TaggedScalar { get, .. } => get(value).ber_encode_tagged(m.tag, content),
            MemberAccess::ExplicitScalar { ber_encode, .. } => ber_encode(value, content),
            MemberAccess::ExplicitAny { ber_encode, .. } => ber_encode(value, content),
            MemberAccess::Unsupported { reason } => panic!("member '{}' not supported: {}", m.name, reason),
        }
    }
}

/// SEQUENCE encoding under an explicit tag override — the runtime
/// counterpart of a composite (SEQUENCE/SET-typed) member declared with its
/// own IMPLICIT `[n]` tag (X.690 §8.14.2): same content as `encode_sequence`,
/// different outer tag. Generic over any `SequenceSpec<T>`, so codegen needs
/// no per-type wiring beyond passing the member's resolved tag.
pub fn encode_sequence_tagged<T>(spec: &SequenceSpec<T>, value: &T, tag: Tag) -> Vec<u8> {
    let mut content = Vec::new();
    encode_sequence_content(spec, value, &mut content);
    let mut out = Vec::new();
    write_constructed(&mut out, tag, &content);
    out
}

/// Appends a SEQUENCE's complete TLV (its own natural tag) to an existing
/// buffer — the shape `Asn1Value::ber_encode` needs (writes into a
/// caller-owned `out`, not a fresh `Vec`) so a generated SEQUENCE/SET type
/// can implement that trait and become usable as a nested composite member.
pub fn encode_sequence_into<T>(spec: &SequenceSpec<T>, value: &T, out: &mut Vec<u8>) {
    out.extend_from_slice(&encode_sequence_tagged(spec, value, spec.tag));
}

/// Generic SEQUENCE encoder — the Rust analogue of
/// `SequenceBerHandler::encode`. Iterates `spec.members` in order, writing
/// each member's own complete TLV into the constructed SEQUENCE content.
/// OPTIONAL suppression needs no special-casing here: an
/// absent `Option<V>::None` member's `ber_encode` (the blanket
/// `Asn1Value for Option<V>` impl, `value.rs`) already writes nothing. No
/// DEFAULT-value suppression yet — a real gap, not silently dropped.
pub fn encode_sequence<T>(spec: &SequenceSpec<T>, value: &T) -> Vec<u8> {
    encode_sequence_tagged(spec, value, spec.tag)
}

/// Generic SEQUENCE decoder — the Rust analogue of
/// `SequenceBerHandler::decode`/`decode_body`. `T::default()` provides the
/// initial value (matching every generated struct's `#[derive(Default)]`);
/// each member is decoded in table order directly into its field via
/// `ber_decode_into`, no intermediate allocation per member.
///
/// OPTIONAL members: tag-presence detection, same model
/// `asn1cpp/CLAUDE.md`'s BER-vs-PER table documents ("OPTIONAL detection:
/// Tag present/absent in stream"). Peek before deciding whether to call
/// `ber_decode_into` at all — an absent optional member's tag belongs to
/// whatever comes *next* (the following member, or nothing), so the reader
/// must not be advanced past it if this member isn't present. Only a linear
/// scan (each optional member checked once, in table order) — correct for
/// SEQUENCE's canonical member ordering (X.690 §8.9), same simplifying
/// assumption `MemberDescriptor`'s module doc already documents this crate
/// making elsewhere (no out-of-order OPTIONAL members). An absent
/// DEFAULT-valued member (`m.set_default` — see `MemberDescriptor`'s own
/// doc) gets its schema default filled in here instead of being left
/// however `T::default()` left it.
pub fn decode_sequence_content<T: Default>(spec: &SequenceSpec<T>, inner: &mut Reader) -> Result<T, DecodeError> {
    let mut result = T::default();
    for m in spec.members {
        match &m.access {
            MemberAccess::Scalar { get_mut, .. } => {
                if m.optional {
                    if inner.peek_tag() == Some(m.tag) {
                        get_mut(&mut result).ber_decode_into(inner)?;
                    } else if let Some(set_default) = m.set_default {
                        set_default(&mut result);
                    }
                } else {
                    get_mut(&mut result).ber_decode_into(inner)?;
                }
            }
            MemberAccess::TaggedScalar { get_mut, .. } => {
                if m.optional {
                    if inner.peek_tag() == Some(m.tag) {
                        get_mut(&mut result).ber_decode_into_tagged(inner, m.tag)?;
                    } else if let Some(set_default) = m.set_default {
                        set_default(&mut result);
                    }
                } else {
                    get_mut(&mut result).ber_decode_into_tagged(inner, m.tag)?;
                }
            }
            MemberAccess::ExplicitScalar { ber_decode_into, .. } => {
                if m.optional {
                    if inner.peek_tag() == Some(m.tag) {
                        ber_decode_into(&mut result, inner)?;
                    } else if let Some(set_default) = m.set_default {
                        set_default(&mut result);
                    }
                } else {
                    ber_decode_into(&mut result, inner)?;
                }
            }
            MemberAccess::ExplicitAny { ber_decode_into, .. } => {
                if m.optional {
                    if inner.peek_tag() == Some(m.tag) {
                        ber_decode_into(&mut result, inner)?;
                    }
                } else {
                    ber_decode_into(&mut result, inner)?;
                }
            }
            MemberAccess::Unsupported { reason } => panic!("member '{}' not supported: {}", m.name, reason),
        }
    }
    Ok(result)
}

/// SEQUENCE decoding under an explicit tag override — the decode
/// counterpart of `encode_sequence_tagged`.
pub fn decode_sequence_tagged<T: Default>(spec: &SequenceSpec<T>, r: &mut Reader, tag: Tag) -> Result<T, DecodeError> {
    let tlv = r.read_tlv()?;
    if tlv.tag != tag {
        return Err(DecodeError::new(format!("expected SEQUENCE tag, got {:?}", tlv.tag), r.pos()));
    }
    let mut inner = Reader::new(tlv.value);
    decode_sequence_content(spec, &mut inner)
}

/// Reads a SEQUENCE (its own natural tag) from the caller's current stream
/// position — the shape `Asn1Value::ber_decode_into` needs (reads the next
/// TLV from a shared `Reader`, not a standalone buffer) so a generated
/// SEQUENCE/SET type can implement that trait and become usable as a nested
/// composite member.
pub fn decode_sequence_from<T: Default>(spec: &SequenceSpec<T>, r: &mut Reader) -> Result<T, DecodeError> {
    decode_sequence_tagged(spec, r, spec.tag)
}

pub fn decode_sequence<T: Default>(spec: &SequenceSpec<T>, data: &[u8]) -> Result<T, DecodeError> {
    let mut r = Reader::new(data);
    decode_sequence_from(spec, &mut r)
}


