#!/usr/bin/env python3
r"""Make the constructed-string BER vectors, with asn1c as the judge.

    make_constructed_vectors.py SCHEMA.asn1 INPUTS.in OUT.vectors

INPUTS.in holds one row per value (# starts a comment):
  xer<TAB>Type<TAB>XER             asn1c encodes the value in CER, which
                                   segments strings longer than 1000 octets
                                   (X.690 §9.2), and in DER
  ber<TAB>Type<TAB>hex<TAB>source  a constructed BER encoding copied from a
                                   standard; asn1c decodes it to DER

OUT.vectors gets one `Type<TAB>source<TAB>BER-hex<TAB>DER-hex` line per
row: a decoder must read BER-hex as the same value as DER-hex, and
re-encode it to DER-hex. Needs asn1c on PATH; the committed .vectors file
needs nothing.
"""
import os
import shutil
import subprocess
import sys
import tempfile


def run(tool, ty, inform, outform, data):
    r = subprocess.run([tool, "-p", ty, f"-i{inform}", f"-o{outform}", "-"], input=data, capture_output=True)
    if r.returncode != 0 or not r.stdout:
        sys.exit(f"asn1c could not convert {ty} {inform}->{outform}: {r.stderr.decode(errors='replace')}")
    return r.stdout


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    schema, inputs, out = (os.path.abspath(a) for a in sys.argv[1:])
    asn1c = shutil.which("asn1c") or sys.exit("asn1c not found on PATH")
    lines = []
    with tempfile.TemporaryDirectory() as work:
        subprocess.run([asn1c, "-fcompound-names", "-fno-include-deps", "-pdu=all", "-D", work, schema],
                       check=True, capture_output=True)
        subprocess.run(["make", "-s", f"-j{os.cpu_count() or 4}", "-C", work, "-f", "converter-example.mk"],
                       check=True, capture_output=True)
        tool = os.path.join(work, "converter-example")
        for line in open(inputs, encoding="utf-8"):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            kind, ty, rest = line.split("\t", 2)
            if kind == "xer":
                xer = rest.encode()
                ber = run(tool, ty, "xer", "cer", xer)
                der = run(tool, ty, "xer", "der", xer)
                source = "asn1c CER"
            elif kind == "ber":
                hexstr, source = rest.split("\t", 1)
                ber = bytes.fromhex(hexstr)
                der = run(tool, ty, "ber", "der", ber)
            else:
                sys.exit(f"unknown row kind {kind!r}")
            if run(tool, ty, "ber", "der", ber) != der:
                sys.exit(f"asn1c reads the {source} encoding of {ty} as a different value")
            lines.append(f"{ty}\t{source}\t{ber.hex().upper()}\t{der.hex().upper()}\n")
    with open(out, "w") as f:
        f.write(f"# Generated by make_constructed_vectors.py from {os.path.basename(inputs)}; do not edit.\n")
        f.writelines(lines)


if __name__ == "__main__":
    main()
