#!/usr/bin/env python3
r"""Turn a list of XER values into BER test vectors, with asn1c as the
encoder: asn1c is the ground truth, so vectors are never written by hand.

    make_ber_vectors.py SCHEMA.asn1 VALUES.xer OUT.vectors

VALUES.xer holds one `Type<TAB>XER` line per value (# starts a comment).
OUT.vectors gets one `Type<TAB>XER<TAB>DER-hex<TAB>asn1c-XER<TAB>asn1c-JER` line per value;
the runtime legs decode the hex, compare with the value, and re-encode it byte
for byte. The last column is asn1c's own XER output for that DER (its exact
BASIC-XER text, for the XER legs) and the next asn1c's JER output for it (for
the JER legs, which compare it as JSON: asn1c indents its JER), both with
backslash, newline and tab written as \\, \n and \t.
Needs asn1c on PATH; the committed .vectors files need nothing.
"""
import os
import shutil
import subprocess
import sys
import tempfile


def escape(text):
    return text.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", "\\t")


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    schema, values, out = (os.path.abspath(a) for a in sys.argv[1:])
    asn1c = shutil.which("asn1c") or sys.exit("asn1c not found on PATH")
    rows = []
    for line in open(values):
        line = line.rstrip("\n")
        if line and not line.startswith("#"):
            rows.append(line.split("\t", 1))
    with tempfile.TemporaryDirectory() as work:
        subprocess.run([asn1c, "-fcompound-names", "-fno-include-deps", "-pdu=all", "-D", work, schema],
                       check=True, capture_output=True)
        subprocess.run(["make", "-s", f"-j{os.cpu_count() or 4}", "-C", work, "-f", "converter-example.mk"],
                       check=True, capture_output=True)
        tool = os.path.join(work, "converter-example")
        lines = []
        for ty, xer in rows:
            src = os.path.join(work, "value.xer")
            with open(src, "w") as f:
                f.write(xer)
            r = subprocess.run([tool, "-p", ty, "-ixer", "-oder", src], capture_output=True)
            if r.returncode != 0 or not r.stdout:
                sys.exit(f"asn1c could not encode {ty} {xer}: {r.stderr.decode(errors='replace')}")
            der = r.stdout
            src = os.path.join(work, "value.der")
            with open(src, "wb") as f:
                f.write(der)
            r = subprocess.run([tool, "-p", ty, "-iber", "-oxer", src], capture_output=True)
            if r.returncode != 0 or not r.stdout:
                sys.exit(f"asn1c could not print {ty} {xer} as XER: {r.stderr.decode(errors='replace')}")
            asn1c_xer = r.stdout.decode()
            r = subprocess.run([tool, "-p", ty, "-iber", "-ojer", src], capture_output=True)
            if r.returncode != 0 or not r.stdout:
                sys.exit(f"asn1c could not print {ty} {xer} as JER: {r.stderr.decode(errors='replace')}")
            lines.append(f"{ty}\t{xer}\t{der.hex().upper()}\t{escape(asn1c_xer)}\t{escape(r.stdout.decode())}\n")
    with open(out, "w") as f:
        f.write(f"# Generated by make_ber_vectors.py from {os.path.basename(values)}; do not edit.\n")
        f.writelines(lines)


if __name__ == "__main__":
    main()
