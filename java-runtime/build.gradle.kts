// Signing is required by Maven Central and runs when a key is given
// (ORG_GRADLE_PROJECT_signingKey / signingPassword, ASCII-armoured).
signing {
    val key = providers.gradleProperty("signingKey").orNull
    if (key != null) {
        useInMemoryPgpKeys(key, providers.gradleProperty("signingPassword").orNull)
        sign(publishing.publications["wire"])
    }
}
